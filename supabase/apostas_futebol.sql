create table if not exists public.apostas_futebol (
  id bigint generated by default as identity primary key,
  fixture_id bigint,
  partida text,
  mercado text,
  odd numeric,
  stake numeric,
  lucro numeric,
  status text not null default 'PENDENTE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.apostas_futebol disable row level security;

create or replace function public.apostas_futebol_touch()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists apostas_futebol_touch on public.apostas_futebol;
create trigger apostas_futebol_touch
  before update on public.apostas_futebol
  for each row
  execute function public.apostas_futebol_touch();
