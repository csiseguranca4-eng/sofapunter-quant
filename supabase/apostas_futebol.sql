create table if not exists public.apostas_futebol (
  id bigint generated by default as identity primary key,
  fixture_id bigint,
  data date,
  jogo text,
  mercado text,
  odd numeric,
  stake numeric,
  lucro numeric,
  status text not null default 'PENDENTE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.apostas_futebol disable row level security;

create or replace function public.apostas_futebol_touch()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

alter table public.apostas_futebol add column if not exists data date;
alter table public.apostas_futebol add column if not exists jogo text;

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'apostas_futebol' and column_name = 'partida'
  ) then
    update public.apostas_futebol set jogo = coalesce(jogo, partida) where jogo is null;
  end if;
end $$;

drop trigger if exists apostas_futebol_touch on public.apostas_futebol;
create trigger apostas_futebol_touch
  before update on public.apostas_futebol
  for each row
  execute function public.apostas_futebol_touch();
